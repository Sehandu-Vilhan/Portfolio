    private void btnSendActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSendActionPerformed
		
		
		
		
      
        
        
        String message = txtSendMsg.getText();
        String selectedUnit = jComboBox1.getSelectedItem().toString();
        
        if (message.trim().isEmpty()) {
            return;
        }
        
        if (btnSendPr.isSelected()) {
            if (selectedUnit.equals("Helicopter")) {
                helicopter.receiveMessage("Main (Private): " + message);
                txtInbox.append("You (Private to Helicopter): " + message + "\n");
            } else if (selectedUnit.equals("Tank")) {
                tank.receiveMessage("Main (Private): " + message);
                txtInbox.append("You (Private to Tank): " + message + "\n");
            } else if (selectedUnit.equals("Submarine")) {
                submarine.receiveMessage("Main (Private): " + message);
                txtInbox.append("You (Private to Submarine): " + message + "\n");
            } else {
                txtInbox.append("Error: Please select a valid defense unit from the dropdown for private messaging.\n");
                return;
            }
        } else {
            helicopter.receiveMessage("Main (Broadcast): " + message);
            tank.receiveMessage("Main (Broadcast): " + message);
            submarine.receiveMessage("Main (Broadcast): " + message);
            txtInbox.append("You (Broadcast): " + message + "\n");
        }
        
        txtSendMsg.setText("");
    }//GEN-LAST:event_btnSendActionPerformed







